if __name__ == "__main__":
    font = Font(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_FONT)
    for name, build in [("IndexedQuadSeq", sequencer), ("SequencerController", controller)]:
        panel = build()
        for theme in THEMES:
            suffix = "" if theme == "light" else "-dark"
            out = os.path.join(ROOT, "res", name + suffix + ".svg")
            panel.write(out, theme, font)
            print("wrote", os.path.relpath(out, ROOT))
